#!/usr/bin/env python3
"""Generate Rust decoders for the V3D 4.2 control-list packets and state records from Mesa's
src/broadcom/cle/v3d_packet.xml (the hardware's only public description).

    python3 tools/gen_v3d_packets.py cache/mesa/src/broadcom/cle/v3d_packet.xml > v3d/src/packets.rs
"""
import re, sys
import xml.etree.ElementTree as ET

VER = 42

def valid(e):
    lo = int(e.get("min_ver", "0")); hi = int(e.get("max_ver", "0"))
    return not (lo and VER < lo) and not (hi and VER > hi)

def ident(name):
    s = re.sub(r"[^0-9a-zA-Z]+", "_", name).strip("_").lower()
    if s[0].isdigit(): s = "f_" + s
    if s in ("type", "mod", "ref", "match", "loop", "fn", "struct", "impl", "use", "in", "box", "move", "self"): s += "_"
    return s

def tname(name):
    return "".join(w.capitalize() for w in re.split(r"[^0-9a-zA-Z]+", name) if w)

root = ET.parse(sys.argv[1]).getroot()
enums = {e.get("name") for e in root.findall("enum")}
out = ["//! Generated by tools/gen_v3d_packets.py from Mesa's src/broadcom/cle/v3d_packet.xml (V3D 4.2).",
       "//! Field offsets are bits from the start of the packet (opcode byte included) or struct.",
       "#![allow(dead_code, unused_variables, clippy::all)]",
       "use crate::bits::*;", ""]
lengths = {}
names = {}

def emit(group, is_packet):
    name = group.get("name")
    fields = []
    for f in group.findall("field"):
        if not valid(f): continue
        start = f.get("start")
        start = int(start[:-1]) * 8 if start.endswith("b") else int(start)
        if is_packet: start += 8
        size = int(f.get("size"))
        fields.append((ident(f.get("name")), start, size, f.get("type"), f.get("minus_one") == "true"))
    length = max([(s + n - 1) // 8 for (_, s, n, _, _) in fields] + [0]) + 1 if fields or is_packet else 0
    sname = tname(name)
    out.append(f"/// {name}")
    out.append("#[derive(Debug, Clone, Copy, Default)]")
    out.append(f"pub struct {sname} {{")
    for (fn, s, n, t, m) in fields:
        rt = {"bool": "bool", "float": "f32", "f187": "f32", "int": "i32"}.get(t)
        if rt is None:
            rt = "f32" if re.match(r"[us]\d+\.\d+", t) else ("u32" if n <= 32 else "u64")
        out.append(f"    pub {fn}: {rt},")
    out.append("}")
    out.append(f"impl {sname} {{")
    out.append(f"    pub const LEN: usize = {length};")
    out.append("    pub fn parse(b: &[u8]) -> Self {")
    out.append("        Self {")
    for (fn, s, n, t, m) in fields:
        if t == "bool": e = f"ubits(b, {s}, {n}) != 0"
        elif t == "address": e = f"(ubits(b, {s}, {n}) << {32 - n}) as u32"
        elif t == "float": e = f"f32::from_bits(ubits(b, {s}, {n}) as u32)"
        elif t == "f187": e = f"f32::from_bits((ubits(b, {s}, {n}) as u32) << 16)"
        elif t == "int": e = f"sbits(b, {s}, {n}) as i32"
        elif re.match(r"u\d+\.\d+", t): e = f"ubits(b, {s}, {n}) as f32 / {1 << int(t.split('.')[1])}.0"
        elif re.match(r"s\d+\.\d+", t): e = f"sbits(b, {s}, {n}) as f32 / {1 << int(t.split('.')[1])}.0"
        else:
            e = f"ubits(b, {s}, {n})" + ("" if n > 32 else " as u32")
        if m: e = f"({e}) + 1"
        out.append(f"            {fn}: {e},")
    out.append("        }")
    out.append("    }")
    out.append("}")
    out.append("")
    if is_packet:
        code = int(group.get("code"))
        lengths[code] = max(lengths.get(code, 0), length)
        names.setdefault(code, name)

for e in root:
    if e.tag in ("packet", "struct") and valid(e):
        emit(e, e.tag == "packet")
    if e.tag == "enum" and valid(e):
        out.append(f"/// {e.get('name')}")
        out.append(f"pub mod {ident(e.get('name'))} {{")
        for v in e.findall("value"):
            if valid(v):
                out.append(f"    pub const {ident(v.get('name')).upper()}: u32 = {v.get('value')};")
        out.append("}")
        out.append("")

out.append("/// Length in bytes (opcode included) of each V3D 4.2 control-list packet, 0 if unknown.")
out.append("pub const PACKET_LEN: [u8; 256] = {")
out.append("    let mut t = [0u8; 256];")
for c in sorted(lengths): out.append(f"    t[{c}] = {lengths[c]}; // {names[c]}")
out.append("    t")
out.append("};")
print("\n".join(out))
