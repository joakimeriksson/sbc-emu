#!/usr/bin/env python3
"""Write an sbc-emu script that copies a test program into a logged-in guest over the serial
console (base64 in short lines, no network needed), builds it with gcc, runs it on the GPU and
on a software renderer in the same guest, and prints the comparison on the console.

  tools/serial_test_script.py tests/gpu/gles2test.c llvmpipe ["scene ..."] > out/rpi3-gles2test.txt
  sbc-emu run --board pi3b --sd cache/os/raspios-gpu.img --restore out/rpi3-v3d.snap \
      --script out/rpi3-gles2test.txt --timeout 3600
"""
import base64, re, sys

src, sw = sys.argv[1], (sys.argv[2] if len(sys.argv) > 2 else "llvmpipe")
name = src.rsplit("/", 1)[-1]
exe = name.rsplit(".", 1)[0]
text = open(src, "rb").read()
data = base64.b64encode(text).decode()
# every scene on its own: one that does not compile on this driver does not stop the rest
scenes = sys.argv[3] if len(sys.argv) > 3 else " ".join(re.findall(r'\{"([a-z0-9_]+)", s_', text.decode()))
out = ["# generated by tools/serial_test_script.py from " + src,
       "serial \\r", "wait-serial pi@raspberrypi",
       "serial stty -echo; rm -rf /tmp/t && mkdir -p /tmp/t/gpu /tmp/t/sw && cd /tmp/t && : > s.b64; echo READY-$((6*7))\\r",
       "wait-serial READY-42"]
step = 400
for k in range(0, len(data), step):
    out.append("serial echo %s >> s.b64; echo C%d-$((1))\\r" % (data[k:k + step], k // step))
    out.append("wait-serial C%d-1" % (k // step))
out += [
    "serial stty echo; base64 -d s.b64 > %s && gcc -O1 -o %s %s -lEGL -lGLESv2 -lm && echo BUILD-$((2*3))\\r" % (name, exe, name),
    "wait-serial BUILD-6",
    "serial for s in %s; do ./%s run gpu $s 2>&1 | grep -v '^renderer'; done; echo GPU-$((7*8))\\r" % (scenes, exe),
    "wait-serial GPU-56",
    "serial for s in %s; do GALLIUM_DRIVER=%s LIBGL_ALWAYS_SOFTWARE=1 ./%s run sw $s; done > sw.log 2>&1; grep -c done sw.log; echo SW-$((8*9))\\r" % (scenes, sw, exe),
    "wait-serial SW-72",
    "serial ./%s cmp gpu sw; echo CMP-$((9*9))\\r" % exe,
    "wait-serial CMP-81",
    "quit",
]
print("\n".join(out))
