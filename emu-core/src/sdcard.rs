//! An SDHC memory card (SD Physical Layer Simplified Specification) shared by the SD/MMC
//! host controllers of every board: card states, CID/CSD/SCR/SD status/SWITCH replies,
//! erase and block range checks. Controllers own their registers and move the data:
//! `command` says what the data phase is; `read_blocks`/`write_blocks` access the disk.
use crate::disk::Disk;

/// Sectors in the unit a card's size is counted in (CSD 2.0: 512 KiB).
pub const UNIT: u64 = 1024;

/// R1 card status bits used here.
pub const OUT_OF_RANGE: u32 = 1 << 31;
pub const READY_FOR_DATA: u32 = 1 << 8;
pub const APP_CMD: u32 = 1 << 5;

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum CardState {
    Idle,
    Ready,
    Ident,
    Standby,
    Transfer,
}

#[derive(Debug, PartialEq, Eq)]
pub enum Response {
    /// R1, R1b, R3, R6, R7: one 32-bit word.
    Short(u32),
    /// R2 (CID, CSD): the 128-bit register, bit 127 first as in the specification
    /// (controllers store it the way their response registers expect).
    Long(u128),
}

#[derive(Debug, PartialEq, Eq)]
pub enum Data {
    None,
    /// Card-generated bytes for the host to read (SCR, SD status, SWITCH status).
    Bytes(Vec<u8>),
    /// A block read from `lba`; the host decides how many blocks (block count, byte count,
    /// or until CMD12).
    Read { lba: u64 },
    /// A block write to `lba`.
    Write { lba: u64 },
}

#[derive(Debug, PartialEq, Eq)]
pub struct Reply {
    /// `None`: the card does not answer (command timeout).
    pub response: Option<Response>,
    pub data: Data,
}

impl Reply {
    fn short(word: u32) -> Self {
        Reply { response: Some(Response::Short(word)), data: Data::None }
    }
    fn timeout() -> Self {
        Reply { response: None, data: Data::None }
    }
}

pub struct SdCard {
    pub disk: Option<Box<dyn Disk>>,
    state: CardState,
    rca: u16,
    app: bool,
    erase: (u32, u32),
    /// Print every command to stderr.
    pub trace: bool,
}

impl SdCard {
    pub fn new(disk: Option<Box<dyn Disk>>) -> Self {
        SdCard { disk, state: CardState::Idle, rca: 0, app: false, erase: (0, 0), trace: false }
    }

    pub fn present(&self) -> bool {
        self.disk.is_some()
    }

    pub fn state(&self) -> CardState {
        self.state
    }

    /// The card's capacity: whole CSD units, never more than the disk stores. (An image of
    /// another size is padded where it is opened: `CowFile::as_card`, the browser's disk.)
    pub fn sectors(&self) -> u64 {
        self.disk.as_ref().map_or(0, |d| d.sectors() / UNIT * UNIT)
    }

    /// R1 card status: current state and READY_FOR_DATA.
    pub fn status(&self) -> u32 {
        let state = match self.state {
            CardState::Idle => 0,
            CardState::Ready => 1,
            CardState::Ident => 2,
            CardState::Standby => 3,
            CardState::Transfer => 4,
        };
        state << 9 | READY_FOR_DATA
    }

    /// Whether `blocks` blocks from `lba` lie on the card.
    pub fn in_range(&self, lba: u64, blocks: u64) -> bool {
        lba.checked_add(blocks).is_some_and(|end| end <= self.sectors())
    }

    pub fn read_blocks(&mut self, lba: u64, out: &mut [u8]) {
        match self.disk.as_mut() {
            Some(disk) => disk.read(lba, out),
            None => out.fill(0),
        }
    }

    pub fn write_blocks(&mut self, lba: u64, data: &[u8]) {
        if let Some(disk) = self.disk.as_mut() {
            disk.write(lba, data);
        }
    }

    pub fn cid(&self) -> u128 {
        // MID 0x5b, OID "SE", name "SBCEM", rev 1.0, serial, date
        0x5b53_4553_4243_454d_1000_5bc0_0001_1ab1
    }

    pub fn csd(&self) -> u128 {
        // CSD version 2.0 (SDHC): C_SIZE in 512 KiB units.
        let c_size = (self.sectors() / 1024).saturating_sub(1) as u128 & 0x3f_ffff;
        1 << 126
            | 0x0e << 112 // TAAC
            | 0x32 << 96 // TRAN_SPEED 25 MHz
            | 0x5b5 << 84 // CCC, including erase (class 5)
            | 9 << 80 // READ_BL_LEN 512
            | c_size << 48
            | 0x7f << 39 // SECTOR_SIZE
            | 2 << 26 // R2W_FACTOR
            | 9 << 22 // WRITE_BL_LEN
            | 1
    }

    /// Execute command `index` (an application command after CMD55).
    pub fn command(&mut self, index: u32, arg: u32) -> Reply {
        let app = std::mem::take(&mut self.app);
        if self.trace {
            eprintln!("[sd card] {}CMD{index} arg={arg:#010x} state={:?}", if app { "A" } else { "" }, self.state);
        }
        if self.disk.is_none() {
            return Reply::timeout();
        }
        let r1 = self.status();
        match (app, index) {
            (_, 0) => {
                self.state = CardState::Idle;
                Reply { response: None, data: Data::None }
            }
            (_, 8) => Reply::short(arg & 0xfff), // R7: voltage accepted, check pattern
            (_, 55) => {
                self.app = true;
                Reply::short(r1 | APP_CMD)
            }
            (true, 41) => {
                if arg & 0x00ff_8000 != 0 && self.state == CardState::Idle {
                    self.state = CardState::Ready;
                }
                // R3: power-up done, CCS (SDHC), 2.7-3.6 V
                Reply::short(0x8000_0000 | 1 << 30 | 0x00ff_8000)
            }
            (_, 2) => {
                self.state = CardState::Ident;
                Reply { response: Some(Response::Long(self.cid())), data: Data::None }
            }
            (_, 3) => {
                self.state = CardState::Standby;
                self.rca = 0x5bc0;
                Reply::short((self.rca as u32) << 16 | 0x0500) // R6
            }
            (_, 9) => Reply { response: Some(Response::Long(self.csd())), data: Data::None },
            (_, 10) => Reply { response: Some(Response::Long(self.cid())), data: Data::None },
            (_, 7) => {
                self.state = if (arg >> 16) as u16 == self.rca { CardState::Transfer } else { CardState::Standby };
                Reply::short(r1)
            }
            (true, 6) | (true, 23) | (true, 42) => Reply::short(r1 | APP_CMD),
            (true, 51) => Reply {
                // SCR: SD 3.0, 1- and 4-bit bus; no CMD20/CMD23 support advertised
                // (SET_BLOCK_COUNT is accepted but not enforced).
                response: Some(Response::Short(r1 | APP_CMD)),
                data: Data::Bytes(vec![0x02, 0x35, 0x80, 0x00, 0, 0, 0, 0]),
            },
            (true, 13) => {
                let mut status = vec![0u8; 64];
                status[0] = 0x80; // 4-bit bus
                Reply { response: Some(Response::Short(r1 | APP_CMD)), data: Data::Bytes(status) }
            }
            (false, 6) => {
                // SWITCH_FUNC status: group 1 supports default and high speed.
                let mut status = vec![0u8; 64];
                status[1] = 0x64; // 100 mA
                status[12] = 0x80;
                status[13] = 0x03;
                status[16] = u8::from(arg & 0xf == 1);
                Reply { response: Some(Response::Short(r1)), data: Data::Bytes(status) }
            }
            (_, 12) | (_, 13) | (_, 16) | (false, 23) => Reply::short(r1),
            // Erase: CMD32/33 set the range, CMD38 erases. Linux uses it for discard, after
            // which the data is undefined, so the blocks keep their contents.
            (false, 32) => {
                self.erase.0 = arg;
                Reply::short(r1)
            }
            (false, 33) => {
                self.erase.1 = arg;
                Reply::short(r1)
            }
            (false, 38) => {
                let (start, end) = self.erase;
                if start > end || end as u64 >= self.sectors() {
                    return Reply::short(r1 | OUT_OF_RANGE);
                }
                Reply::short(r1)
            }
            (_, 17) | (_, 18) | (_, 24) | (_, 25) => {
                let lba = arg as u64;
                if lba >= self.sectors() {
                    return Reply::short(r1 | OUT_OF_RANGE);
                }
                let data = if index <= 18 { Data::Read { lba } } else { Data::Write { lba } };
                Reply { response: Some(Response::Short(r1)), data }
            }
            _ => Reply::timeout(),
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::disk::MemDisk;

    fn ready_card() -> SdCard {
        let mut card = SdCard::new(Some(Box::new(MemDisk::new(2048))));
        card.command(0, 0);
        card.command(8, 0x1aa);
        card.command(55, 0);
        card.command(41, 0x40ff_8000);
        card.command(2, 0);
        card.command(3, 0);
        card.command(7, 0x5bc0 << 16);
        card
    }

    #[test]
    fn initialisation_reaches_transfer_state() {
        let card = ready_card();
        assert_eq!(card.state(), CardState::Transfer);
        assert_eq!(card.csd() >> 48 & 0x3f_ffff, 1, "2048 sectors = 2 x 512 KiB");
    }

    #[test]
    fn the_card_offers_whole_units_of_what_is_stored() {
        for (sectors, capacity) in [(2048u64, 2048), (2049, 2048), (3071, 2048), (3072, 3072)] {
            let card = SdCard::new(Some(Box::new(MemDisk::new(sectors))));
            assert_eq!(((card.csd() >> 48 & 0x3f_ffff) as u64 + 1) * 1024, capacity);
            assert!(card.in_range(capacity - 1, 1) && !card.in_range(capacity, 1));
        }
    }

    #[test]
    fn erase_and_range_checks() {
        let mut card = ready_card();
        assert_eq!(card.command(32, 10), Reply::short(card.status()));
        card.command(33, 20);
        assert_eq!(card.command(38, 0).response, Some(Response::Short(card.status())));
        card.command(32, 0);
        card.command(33, 4096);
        assert_ne!(card.command(38, 0), Reply::short(card.status()));
        assert_eq!(card.command(17, 2047).data, Data::Read { lba: 2047 });
        assert!(matches!(card.command(18, 2048).response, Some(Response::Short(s)) if s & OUT_OF_RANGE != 0));
        assert!(card.in_range(2040, 8) && !card.in_range(2040, 9));
    }

    #[test]
    fn absent_card_times_out() {
        let mut card = SdCard::new(None);
        assert_eq!(card.command(8, 0x1aa).response, None);
    }
}
